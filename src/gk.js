/* Draw without repeats: each tier is a shuffled deck, refilled when used up. */
const decks = { 1: [], 2: [], 3: [] };
function shuffle(a) {
  for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(Math.random() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; }
  return a;
}

export function gkTierFor(correctCount) {
  return correctCount < 20 ? 1 : correctCount < 60 ? 2 : 3;
}

export function genGkQuestion(tier) {
  const t = Math.max(1, Math.min(3, tier));
  // 30% of the time drop one tier, so it never feels relentless
  const use = t > 1 && Math.random() < 0.3 ? t - 1 : t;
  if (!decks[use].length) decks[use] = shuffle(GK_BANK.map((q, i) => i).filter((i) => GK_BANK[i][0] === use));
  const [, cat, text, answer, ...wrongs] = GK_BANK[decks[use].pop()];
  const choices = shuffle([answer, ...wrongs]);
  return { text, answer, choices, op: "gk", cat, tier: use };
}
